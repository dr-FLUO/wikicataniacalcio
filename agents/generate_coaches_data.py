def run_generation() -> None:
    from models import VaultComplianceLinter
    base_dir = Path(__file__).resolve().parent.parent
    allenatori_dir = base_dir / "content" / "tesserati" / "allenatori"
    allenatori_dir.mkdir(parents=True, exist_ok=True)
    registry_path = base_dir / "data" / "entity_registry.json"

    # 1. Update registry
    with open(registry_path, "r", encoding="utf-8") as f:
        registry_data = json.load(f)

    entities = registry_data.get("entities", {})

    created_count = 0
    updated_registry_count = 0

    for c in COACHES_RAW:
        slug = c["slug"]
        full_slug = f"tesserati/allenatori/{slug}"
        md_path = allenatori_dir / f"{slug}.md"

        # Register in entity registry
        aliases = c.get("aliases", [])
        if not aliases:
            last_name = c["name"].split()[-1]
            aliases = [last_name]
        
        entities[full_slug] = {
            "entity_type": "allenatore",
            "canonical_name": c["name"],
            "aliases": aliases
        }
        updated_registry_count += 1

        # Write markdown file
        md_text = build_markdown(c)
        md_path.write_text(md_text, encoding="utf-8")

        # Immediate audit
        audit = VaultComplianceLinter.audit_file(md_path)
        if not audit.is_valid:
            raise AssertionError(f"Errore audit su {md_path}: {audit.errors}")

        created_count += 1

    registry_data["entities"] = entities
    with open(registry_path, "w", encoding="utf-8") as f:
        json.dump(registry_data, f, ensure_ascii=False, indent=2)

    print(f"[OK] Creati e verificati con successo {created_count} file markdown in content/tesserati/allenatori/")
    print(f"[OK] Aggiornato data/entity_registry.json con {updated_registry_count} nuove entita' (Totale: {len(entities)})")



if __name__ == "__main__":
    run_generation()

