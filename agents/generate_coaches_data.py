def sanitize_quotes(s: str) -> str:
    """Sostituisce le virgolette doppie con virgolette caporali « e » o apici singoli."""
    if not s:
        return s
    res = []
    in_quotes = False
    for ch in s:
        if ch == '"':
            if not in_quotes:
                res.append('«')
                in_quotes = True
            else:
                res.append('»')
                in_quotes = False
        else:
            res.append(ch)
    out = "".join(res)
    if in_quotes:
        out = out.replace('«', "'")
    return out

